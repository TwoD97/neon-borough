import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const code=await readFile(new URL('../usage-alerts.js',import.meta.url),'utf8');
const {usageAlerts}=await import(`data:text/javascript,${encodeURIComponent(code)}`);
const now=1794120000000,reset=now+3600000;
const provider=(overrides={})=>({id:'codex',name:'Codex',available:true,authenticated:true,account:'one@example.test',windows:[{label:'Weekly',used:90,reset}],...overrides});
const check=(p,state=null,time=now)=>usageAlerts({providers:[p]},state,time);
let first=check(provider());
assert.equal(first.alerts.length,1,'90% alerts on first known current quota');
assert.equal(first.alerts[0].message.level,'warning');
assert.equal(check(provider(),JSON.parse(JSON.stringify(first.state))).alerts.length,0,'Persisted reopen does not repeat');
let full=check(provider({windows:[{label:'Weekly',used:100,reset}]}),first.state);
assert.equal(full.alerts.length,1,'100% escalates once after 90%');
assert.equal(full.alerts[0].message.level,'error');
assert.equal(check(provider(),full.state).alerts.length,0,'Lower later report does not repeat 90%');
assert.equal(check(provider({windows:[{label:'Weekly',used:100,reset}]}),full.state).alerts.length,0);
assert.equal(check(provider({windows:[{label:'Weekly',used:100,reset}]})).alerts.length,1,'Initial exhausted window emits only the highest threshold');
assert.equal(check(provider({windows:[{label:'Weekly',used:90,reset:reset+3600000}]}),full.state).alerts.length,1,'New reset identifies a new quota period');
assert.equal(check(provider(),full.state,reset).state.seen.length,0,'Expired periods are removed');
for(const used of [null,undefined,NaN,Infinity,89.9,101])assert.equal(check(provider({windows:[{label:'Weekly',used,reset}]})).alerts.length,0);
for(const time of [null,undefined,NaN,Infinity,now,now-1])assert.equal(check(provider({windows:[{label:'Weekly',used:100,reset:time}]})).alerts.length,0);
for(const override of [{stale:true},{available:false},{authenticated:false},{authenticated:null},{error:'Unavailable'},{account:''}])assert.equal(check(provider(override)).alerts.length,0);
let baseline=check(provider({windows:[]}));
assert.equal(baseline.alerts.length,0,'Initial account discovery is silent');
assert.equal(check(provider({account:'ONE@example.test',windows:[]}),baseline.state).alerts.length,0,'Account label casing does not signal a switch');
let changed=check(provider({account:'two@example.test',windows:[]}),baseline.state);
assert.equal(changed.alerts.length,1,'Observed account change announces once');
assert.match(changed.alerts[0].message.body,/Running chats may still use/);
assert.equal(check(provider({account:'two@example.test',windows:[]}),changed.state).alerts.length,0);
let unavailable=check(provider({authenticated:false,account:'',windows:[]}),baseline.state);
assert.equal(check(provider({account:'two@example.test',windows:[]}),unavailable.state).alerts.length,1,'Unknown sign-in does not erase the previously known account');
const stale=check(provider({account:'two@example.test',stale:true}),baseline.state);
assert.equal(stale.state.accounts.codex,'one@example.test','Stale data cannot change known account');
const multi=usageAlerts({providers:[provider(),provider({id:'claude',name:'Claude Code',windows:[{label:'5 hour',used:95,reset},{label:'Weekly',used:95,reset}]})]},null,now);
assert.equal(multi.alerts.length,3,'Providers and individual windows have distinct thresholds');
assert.equal(new Set(multi.alerts.map(a=>a.key)).size,3);
assert.deepEqual(first.state.seen[0].threshold,90,'Decisions do not mutate prior state');
console.log('PASS usage alerts: threshold escalation, persisted dedupe, reset periods, unknown/stale suppression, account observation, independent windows.');
