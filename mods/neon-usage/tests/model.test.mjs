import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const code=await readFile(new URL('../model.js',import.meta.url),'utf8');
const {number,quota,timestamp,normalizeSnapshot,tokenLabel,tokenMetrics,reportedLabel,resetLabel,refreshDue}=await import(`data:text/javascript,${encodeURIComponent(code)}`);
for(const bad of [null,undefined,'',true,false,' ',{},NaN,Infinity,-1])assert.equal(number(bad),null);
assert.equal(number(0),0);assert.equal(number('1250'),1250);
assert.equal(quota(0),0);assert.equal(quota(100),100);assert.equal(quota(101),null);
const epoch=1794120000000;
assert.equal(timestamp(epoch),epoch);assert.equal(timestamp(epoch/1000),epoch);assert.equal(timestamp(new Date(epoch).toISOString()),epoch);
assert.equal(resetLabel(epoch+61*60000,epoch),'Resets in 1h 1m');
assert.equal(resetLabel(epoch-1000,epoch),'Reset due · refresh to verify');
assert.equal(tokenLabel(null),'Not reported');assert.equal(tokenLabel(0),'0');
assert.equal(tokenLabel(undefined),'Not reported');
assert.throws(()=>normalizeSnapshot({}),/unexpected response/);
const snapshot=normalizeSnapshot({updated_ms:epoch,providers:[{id:'codex',available:true,account:{authenticated:true,label:'Preview account'},windows:[{label:'Weekly',used_percent:0,resets_at:epoch/1000}],usage:{today_tokens:0},can_switch:true}]});
assert.equal(snapshot.updated,epoch);
assert.equal(snapshot.providers[0].windows.length,1,'Do not invent a five-hour window');
assert.equal(snapshot.providers[0].windows[0].used,0);
assert.equal(snapshot.providers[0].session,null,'Absent tokens must not become zero');
assert.equal(snapshot.providers[1].available,false);
assert.match(snapshot.providers[1].error,/not included/);
assert.equal(snapshot.providers[1].canSwitch,false);
const context=normalizeSnapshot({providers:[{id:'claude',usage:{context_tokens:54000}}]}).providers[1];
assert.equal(context.context,54000);assert.equal(context.session,null,'Context must not become a session lifetime total');
assert.deepEqual(tokenMetrics({id:'codex',today:null,session:null,context:null}),[]);
assert.deepEqual(tokenMetrics({id:'codex',today:0,session:null,context:null}),[['TODAY',0]]);
assert.deepEqual(tokenMetrics(context),[['CONTEXT',54000]]);
const old=normalizeSnapshot({providers:[{id:'claude',updated_ms:epoch,stale:true}]}).providers[1];
assert.equal(old.updated,epoch);assert.equal(old.stale,true);
assert.equal(reportedLabel(old.updated,old.stale,epoch+3600000),'Stale · Reported 1h ago');
assert.equal(refreshDue(60000,0,true,true,false),true);
for(const args of [[59999,0,true,true,false],[60000,0,false,true,false],[60000,0,true,false,false],[60000,0,true,true,true]])assert.equal(refreshDue(...args),false);
console.log('PASS usage model: unknown vs zero, dynamic windows, timestamp units, reset countdowns, and focused refresh gating.');
